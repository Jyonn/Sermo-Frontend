import {createRoot} from 'react-dom/client';
import {BrowserRouter} from 'react-router-dom';
import {AuthProvider} from '../../src/lib/auth';
import {LanguageProvider} from '../../src/lib/language';
import {ThemeProvider} from '../../src/lib/theme';
import {authStorage} from '../../src/lib/storage';
import {activateLanguage} from '../../src/lib/i18n';
import App from '../../src/App';
import {AdminAuthProvider} from '../../src/lib/adminAuth';
import {PlatformAdminAuthProvider} from '../../src/lib/platformAdminAuth';
import {FeatureDiscoveryProvider} from '../../src/lib/featureDiscovery';
import {MusicPlayerProvider} from '../../src/lib/musicPlayer';
import '../../styles.css';
const response=await fetch('http://127.0.0.1:8033/qa/session/');
if(!response.ok)throw Error('Isolated research QA server unavailable');
const session=await response.json();
const theme=new URLSearchParams(location.search).get('theme');
if(theme==='light'||theme==='dark')localStorage.setItem('sermo:theme-preference',theme);
history.replaceState(null,'','/app/research');
authStorage.set(session);
await activateLanguage('zh-CN');
await document.fonts.load('24px "Material Symbols Outlined"');
document.documentElement.classList.add('material-symbols-ready');
createRoot(document.getElementById('root')!).render(<BrowserRouter><AdminAuthProvider><PlatformAdminAuthProvider><AuthProvider><LanguageProvider><ThemeProvider><FeatureDiscoveryProvider><MusicPlayerProvider><App/></MusicPlayerProvider></FeatureDiscoveryProvider></ThemeProvider></LanguageProvider></AuthProvider></PlatformAdminAuthProvider></AdminAuthProvider></BrowserRouter>);
